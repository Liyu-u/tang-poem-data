export function starProfile(name: string): StarProfile {
  const [type, style, color, form, reason] = profiles[name] ?? [
    "银白恒星",
    "诗风待考",
    "#d4dfed",
    "quiet",
    "以中性的银白星光呈现，诗风与星体意象仍待进一步整理。",
  ];
  return {
    type,
    style,
    color,
    form,
    reason,
    size:
      name === "李白"
        ? 1.45
        : form === "giant"
          ? 1.25
          : form === "nebula"
            ? 1.12
            : 0.9,
  };
}
