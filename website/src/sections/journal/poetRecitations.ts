export const poetRecitations: Record<string, PoetVerse[]> = Object.fromEntries(
  Object.entries(selections).map(([id, { author, lines }]) => [id, lines.map(([text, title]) => ({
    text, title, source: `https://www.gushiwen.cn/mingjus/default.aspx?astr=${encodeURIComponent(author)}`,
  }))]),
);

export function pickPoetVerse(id: string, previous?: PoetVerse): PoetVerse | undefined {
  const pool = (poetRecitations[id] ?? []).filter(verse => verse !== previous);
  return pool[Math.floor(Math.random() * pool.length)];
}
